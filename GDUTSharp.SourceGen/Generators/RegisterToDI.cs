using System.Collections.Immutable;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace GDUTSharp.SourceGen.Generators;

[Generator]
public class RegisterToDI : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var provider = context.SyntaxProvider.ForAttributeWithMetadataName
                (
                    GenConstant.RegisterToDI,
                    static (node, token) => node is ClassDeclarationSyntax or StructDeclarationSyntax,
                    (GeneratorAttributeSyntaxContext syntaxContext, CancellationToken token) => GetTypeToGenerate(syntaxContext)
                ).Collect();
        context.RegisterSourceOutput(provider, static (spc, di) => ExecuteGeneration(spc, di));
    }

    private class DIInfo(string interfaceName, string implServiceName)
    {
        public readonly string InterfaceName = interfaceName;
        public readonly string ImplServiceName = implServiceName;
    }

    private DIInfo? GetTypeToGenerate(GeneratorAttributeSyntaxContext ctx)
    {
        foreach (var attr in ctx.Attributes)
        {
            var args = attr.ConstructorArguments;
            string? interfaceName = args.Length == 1 ? args[0].Value as string : null;
            if (interfaceName is null) continue;
            return new(interfaceName, ctx.TargetSymbol.Name);
        }
        return null;
    }

    private static void ExecuteGeneration(SourceProductionContext spc, ImmutableArray<DIInfo?> di)
    {
        StringBuilder sb = new();
        sb.Append("""
            // <auto-generated/>
            using GDUTSharp.Interfaces;
            using GDUTSharp.Services;
            using Microsoft.Extensions.Configuration;
            using Microsoft.Extensions.DependencyInjection;

            namespace GDUTSharp;

            static partial class Extensions
            {
                /// <summary>将所有 GDUTSharp 服务以单例模式注册到 <see cref="IServiceCollection"/> 中</summary>
                /// <remarks>
                /// <see cref="CommonClient"/> 的注册方式由 <see cref="CommonClientExtensions.AddCommonClient(IServiceCollection, IConfiguration)"/> 实现
                /// </remarks>
                static partial IServiceCollection AddGDUTSharp(this IServiceCollection services, IConfiguration configuration)
                {

            """);
        foreach (var item in di)
        {
            if (item is null)  continue;
            sb.Append($"        services.AddSingleton<{item.InterfaceName}, {item.ImplServiceName}>();\n");
        }
        sb.Append("""
                    services.AddCommonClient(configuration);
                    return services;
                }
            }
            """);
        spc.AddSource("Extensions.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
